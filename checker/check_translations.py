RELEASE_TAG_RE = re.compile(r"^v(\d+)\.(\d+)\.(\d+)$")


def _upstream_release_tags(engine_root):
    # {(major, minor, patch): commit sha} for every vX.Y.Z tag on the
    # upstream remote. ls-remote lists an annotated tag twice — the tag
    # object as refs/tags/vX and the commit it points at as refs/tags/vX^{} —
    # so the peeled entry wins where present (lightweight tags have only the
    # plain entry, which already is the commit).
    remote = subprocess.run(
        ["git", "-C", str(engine_root), "ls-remote", "--tags", "origin"],
        capture_output=True, text=True, timeout=30)
    if remote.returncode != 0:
        return None
    plain, peeled = {}, {}
    for line in remote.stdout.splitlines():
        sha, _, ref = line.partition("\t")
        if not ref.startswith("refs/tags/"):
            continue
        name = ref[len("refs/tags/"):]
        target = peeled if name.endswith("^{}") else plain
        target[name.removesuffix("^{}")] = sha
    tags = {}
    for name, sha in plain.items():
        m = RELEASE_TAG_RE.match(name)
        if m:
            tags[tuple(int(g) for g in m.groups())] = peeled.get(name, sha)
    return tags


def check_engine_pin_freshness(report, strict):
    # The engine checkout IS the version contract: consuming repos pin this
    # repo as their l10n/ submodule, and nothing else ever compares that pin
    # to upstream — CI checks out whatever is pinned, and the release skills
    # run whatever is checked out. So the checker, which every gate already
    # runs, verifies its own checkout against upstream's release tags
    # (vMAJOR.MINOR.PATCH; see the upstream CLAUDE.md for what each part
    # means). The policy this enforces: pins move only at release, at the
    # start of a translation pass, or when a new major lands — never per
    # upstream commit, so a stable mod's history is not littered with pin
    # bumps. Hence a MAJOR lag (the shim/flow contract changed) or a pin on
    # an untagged commit warns always; a minor/patch lag warns only under
    # --strict, where a release gate must be on the latest tag, and is a
    # note otherwise. Offline and non-git-checkout states (release tarballs)
    # skip with a note, never a warning: a network flake must not fail a
    # gate --strict would otherwise pass. L10N_SKIP_PIN_CHECK=1 skips
    # explicitly.
    if os.environ.get("L10N_SKIP_PIN_CHECK"):
        return
    engine_root = Path(__file__).resolve().parent.parent
    label = "[l10n engine pin]"
    if not (engine_root / ".git").exists():
        print(f"note: {engine_root} is not a git checkout; skipping engine "
              f"pin freshness check.")
        return
    try:
        local = subprocess.run(
            ["git", "-C", str(engine_root), "rev-parse", "HEAD"],
            capture_output=True, text=True, timeout=10)
        tags = _upstream_release_tags(engine_root)
    except (OSError, subprocess.TimeoutExpired):
        print("note: git unavailable or upstream unreachable; skipping "
              "engine pin freshness check.")
        return
    if local.returncode != 0 or tags is None:
        print("note: could not reach the rimworld-l10n upstream (offline?); "
              "skipping engine pin freshness check.")
        return
    if not tags:
        print("note: upstream rimworld-l10n has no vX.Y.Z release tags; "
              "skipping engine pin freshness check.")
        return
    local_sha = local.stdout.strip()
    fmt = lambda v: "v" + ".".join(str(n) for n in v)  # noqa: E731
    latest = max(tags)
    pinned = [v for v, sha in tags.items() if sha == local_sha]
    if not pinned:
        report.warn(label,
                    f"engine checkout {local_sha[:9]} at {engine_root} is not "
                    f"a tagged rimworld-l10n release (latest is {fmt(latest)}) "
                    f"— pin a release tag: l10n/tools/bump-consumer.sh")
        return
    current = max(pinned)
    if current == latest:
        return
    if current[0] < latest[0]:
        report.warn(label,
                    f"pinned {fmt(current)} is a MAJOR behind upstream "
                    f"{fmt(latest)}: the shim/flow contract changed — bump "
                    f"the pin (l10n/tools/bump-consumer.sh) and apply the "
                    f"per-repo edit the upstream release notes describe")
    elif strict:
        report.warn(label,
                    f"pinned {fmt(current)} is behind upstream {fmt(latest)} "
                    f"— releases run on the latest tag: "
                    f"l10n/tools/bump-consumer.sh")
    else:
        print(f"note: l10n pin {fmt(current)} is behind upstream "
              f"{fmt(latest)} (minor/patch; bumped at the next release or "
              f"translation pass).")


# LoadFolders.xml <li> attributes, as the game evaluates them
# (decompile-verified, Verse.LoadFolder.ShouldLoad): IfModActive = ANY listed
# package active, IfModActiveAll = ALL active, IfModNotActive = NONE active.
# Ids compare lowercase with the "_steam" postfix stripped; a bare <li>
# always loads.
LOAD_FOLDER_ATTRS = (("IfModActive", "any"), ("IfModActiveAll", "all"),
                     ("IfModNotActive", "not"))


def package_ids(text):
    return {p.strip().lower().removesuffix("_steam")
            for p in text.split(",") if p.strip()}


def load_folders(root):
    # LoadFolders.xml as {resolved load root: [condition, ...]}, one
    # condition per <li> listing the root under any version node (a root
    # listed twice loads if either entry passes). A condition is
    # {"any"|"all"|"not": set of ids, "raw": [(attribute, lowercased value
    # as written)]}. None when the mod has no (readable) LoadFolders.xml:
    # every root then loads.
    path = root / "LoadFolders.xml"
    if not path.is_file():
        return None
    try:
        tree = ET.parse(path).getroot()
    except ET.ParseError:
        return None
    folders = {}
    for version in tree:
        for li in version.findall("li"):
            text = (li.text or "").strip().strip("/")
            cond = {"raw": []}
            for attr, kind in LOAD_FOLDER_ATTRS:
                value = li.get(attr)
                if value is not None:
                    cond[kind] = package_ids(value)
                    cond["raw"].append((attr, value.strip().lower()))
            folders.setdefault((root / text).resolve(), []).append(cond)
    return folders


def condition_holds(cond, packages):
    return (not cond.get("any") or bool(cond["any"] & packages)) \
        and (not cond.get("all") or cond["all"] <= packages) \
        and not cond.get("not", set()) & packages


def describe_gate(conds):
    # The gate as a reader would grep LoadFolders.xml for it: a plain
    # IfModActive gate reads as its id list, anything else as attributes.
    raws = [c["raw"] for c in conds if c["raw"]]
    if not raws:
        return None
    if all(len(r) == 1 and r[0][0] == "IfModActive" for r in raws):
        return " / ".join(r[0][1] for r in raws)
    return " / ".join(" ".join(f'{a}="{v}"' for a, v in r) for r in raws)


def check_sidecar_freshness(defs, sidecar, report, def_roots, gates):
    # The rule that makes stale expectations loud: every def carrying a
    # label/description in XML must appear in the sidecar, so new or edited
    # translatable content forces a regen, and the regen sees everything the
    # game sees. The probe dumps only defs with at least one possible
    # injection point, so defs with NO translatable text in XML (most
    # DutyDefs, PrefabDefs, ...) are legitimately absent and tolerated —
    # whether or not their def type has other entries.
    #
    # A def missing from the sidecar because it lives under a LoadFolders-
    # gated compat root whose gate no probe boot activated is the same
    # staleness with a different fix: the gate belongs in the refresh shim's
    # boot list (CANONICAL_ACTIVE_MODS, or a WORLDS entry when the sidecar
    # records worlds), so say so instead of sending the reader to a regen
    # that would come back identical. gates maps each load root inactive in
    # this world to its gate; main() checks a root no world activates in
    # every world, which is the only way such a def reaches this check.
    label = "[Scripts/expected-injections.json]"
    stale = (f"expectations stale — rerun "
             f"Scripts/refresh-translation-expectations.py")
    boot_list = "a WORLDS entry" if "worlds" in (sidecar.parent or sidecar).meta \
        else "CANONICAL_ACTIVE_MODS"

    def why_absent(def_type, def_name):
        owner = def_roots.get(def_type, {}).get(def_name)
        gate = gates.get(owner.resolve()) if owner is not None else None
        if gate:
            return (f"it is declared under the compat root {owner}, gated "
                    f"on {gate}, which was not active during the probe boot "
                    f"— add the gate to {boot_list} in "
                    f"Scripts/refresh-translation-expectations.py, then "
                    f"rerun it")
        return stale

    for def_type, by_name in sorted(defs.items()):
        if def_type not in sidecar.def_types:
            for def_name, elem in sorted(by_name.items()):
                if elem.find("label") is not None \
                        or elem.find("description") is not None:
                    report.error(label, f"{def_type} {def_name} has a label/"
                                        f"description but its def type has no "
                                        f"sidecar entries; "
                                        f"{why_absent(def_type, def_name)}")
            continue
        # English drift: a label/description added or edited in XML without a
        # regen. (Literal-\n unescaping lives in norm().) A world whose
        # variant rewrote the English got it from a gated Patch this scan
        # does not apply, so only the unvaried worlds compare against XML.
        for def_name, elem in sorted(by_name.items()):
            for field in ("label", "description"):
                node = elem.find(field)
                if node is None:
                    continue
                entry = sidecar.entries[def_type].get(f"{def_name}.{field}")
                if entry is None:
                    report.error(label, f"{def_type} {def_name}.{field} is in "
                                        f"the def XML but not the sidecar; "
                                        f"{why_absent(def_type, def_name)}")
                elif "english" in entry.get("variants", {}).get(sidecar.world, {}):
                    continue
                elif norm(entry["english"]) != norm(node.text):
                    report.error(label, f"{def_type} {def_name}.{field} "
                                        f"English differs between def XML and "
                                        f"sidecar; {stale}")


def check_english_definjected(lang_dir, sidecar, def_roots, seen, report):
    # English DefInjected files inject into defs at runtime exactly like any
    # other language's, so an unknown key here is a live "found no def named
    # ..." startup error, not just translator noise — historically these files
    # were only read as reference material and never validated themselves.
    # Every entry must be a legal injection point per the sidecar, its text
    # must match the sidecar's English (drift means the file or the def was
    # edited without a regen), and a key may only be injected once across all
    # English roots (the game dedups by normalizedPath and warns). `seen` is
    # shared across roots: def_type -> key -> first path.
    inj_dir = lang_dir / "DefInjected"
    if not inj_dir.is_dir():
        return
    for type_dir in sorted(p for p in inj_dir.iterdir() if p.is_dir()):
        def_type = type_dir.name
        if def_type not in sidecar.def_types:
            report.error(f"[English/DefInjected/{def_type}]",
                         f"unknown def type folder (no legal injection "
                         f"points in the sidecar)")
            continue
        for path in sorted(type_dir.glob("**/*.xml")):
            for key, elem, _ in load_language_xml(path, report) or []:
                by_key = seen.setdefault(def_type, {})
                if key in by_key:
                    report.error(path, f"duplicate key <{key}> (also in "
                                       f"{by_key[key]})")
                    continue
                by_key[key] = path
                hit = sidecar.lookup(def_type, key)
                if hit is None:
                    report.error(path, elsewhere_note(sidecar, def_type, key,
                                                      "English")
                                 or f"unknown key <{key}> (not a legal "
                                    f"injection point per the sidecar)")
                    continue
                canonical, idx = hit
                if not sidecar.conditional(def_type, canonical):
                    check_entry_root(def_roots, def_type, canonical,
                                     lang_dir.parent.parent, path, report)
                entry = sidecar.entries[def_type][canonical]
                text = flatten_entry(elem)
                if idx is not None:
                    expected = entry["english"][idx]
                elif entry.get("isCollection"):
                    if not isinstance(text, list):
                        report.error(path, f"<{key}> is a collection entry; "
                                           f"expected a <li> list or "
                                           f"element-wise {key}.N keys")
                        continue
                    if len(text) != len(entry["english"]):
                        report.error(path, f"<{key}> has {len(text)} "
                                           f"elements, sidecar English has "
                                           f"{len(entry['english'])}")
                        continue
                    for i, (got, exp) in enumerate(zip(text, entry["english"])):
                        if norm(got) != norm(exp):
                            report.error(path, f"<{key}.{i}> drifted from "
                                               f"sidecar English {exp!r} — "
                                               f"rerun the refresh script or "
                                               f"fix the entry")
                    continue
                else:
                    expected = entry["english"]
                if isinstance(text, list):
                    report.error(path, f"<{key}> is scalar per the sidecar "
                                       f"but holds a <li> list")
                elif norm(text) != norm(expected):
                    report.error(path, f"<{key}> drifted from sidecar "
                                       f"English {expected!r} — rerun the "
                                       f"refresh script or fix the entry")


def elsewhere_note(sidecar, def_type, key, lang):
    # For a key that is no injection point in this world's view but is one
    # in another world: say which worlds it lives in and where it belongs,
    # since "typo or stale" would send the reader to a pointless regen.
    worlds = sidecar.worlds_of(def_type, key) if sidecar.parent else None
    if not worlds:
        return None
    hint = sidecar.where_hint(worlds, lang) or (
        " — translate it in a load root active in exactly those worlds")
    return (f"<{key}>: not an injection point in this configuration (the "
            f"key exists only in worlds {', '.join(worlds)}){hint}")


def check_language(lang_dirs, english_keyed, sidecar, def_roots, report,
                   lang=None):
    # Returns {def_type: set(canonical keys/elements)} actually translated in
    # this language, for the cross-language parity check in main(). Element
    # translations are recorded as "<canonical collection key>.<index>".
    #
    # lang_dirs is EVERY root this language occupies, checked as one unit the
    # way English already is (and the way the game loads them). A gated compat
    # root is not a language of its own: a compat-root trait's injections can
    # only live under 1.6/Mods/<Mod Name>/Languages/<Lang>/ (MayRequire
    # is ignored on DefInjected, so the LoadFolders gate has to be the folder),
    # yet the sidecar marks them required — checking that root standalone would
    # demand the whole Keyed set and every other def's injections from it.
    # With worlds, lang_dirs is the roots active in the view's world, and may
    # be empty (lang then names the language).
    lang = lang or lang_dirs[0].name

    # --- Cross-root file-path collisions ---
    # The game dedups language files per ModContentPack by their path relative
    # to the language folder (decompile-verified 2026-08-19,
    # Verse.LoadedLanguage.TryRegisterFileIfNew): when two load roots of the
    # same mod carry the same relative path (Keyed/ or DefInjected/ alike),
    # only the first-enumerated file loads and the other is SILENTLY skipped —
    # no load error, no translation-report entry, and the enumeration order is
    # not LoadFolders order, so which side wins is not even stable by
    # construction. Every file under a compat root must therefore have a
    # basename path that exists in no other root of the same language. UMW
    # shipped 27 shadowed files across 9 languages before this check existed.
    rel_seen = {}
    for lang_dir in lang_dirs:
        for path in sorted(lang_dir.glob("**/*.xml")):
            rel = path.relative_to(lang_dir)
            if rel in rel_seen:
                report.error(path, f"language-relative path {rel} collides with "
                                   f"{rel_seen[rel]} — the game loads only one of "
                                   f"the two files and silently skips the other "
                                   f"(Verse.LoadedLanguage.TryRegisterFileIfNew "
                                   f"dedups per mod by this path); rename one file")
            else:
                rel_seen[rel] = path

    # --- Keyed ---
    keyed = collect_keyed(lang_dirs, report)
    label = f"[{lang}/Keyed]"
    for key in sorted(set(english_keyed) - set(keyed)):
        report.error(label, f"missing key <{key}>")
    for key, (_, _, path) in sorted(keyed.items()):
        if key not in english_keyed:
            report.error(path, f"unknown key <{key}> (not in English)")
            continue
        text, en, _ = keyed[key]
        en_text = english_keyed[key][0]
        if isinstance(text, str) and isinstance(en_text, str):
            if placeholders(text) != placeholders(en_text):
                report.error(path, f"<{key}> placeholders {sorted(placeholders(text))} "
                                   f"!= English {sorted(placeholders(en_text))}")
        elif isinstance(text, list) and isinstance(en_text, str) \
                or isinstance(text, str) and isinstance(en_text, list):
            report.error(path, f"<{key}> is a <li> list where English is "
                               f"scalar, or vice versa")
        if en is None:
            report.warn(path, f"<{key}> has no EN: comment")
        elif isinstance(en_text, str) and norm(en) != norm(en_text):
            report.error(path, f"<{key}> is STALE: EN comment does not match current "
                               f"English text")
        elif isinstance(en_text, list) and not en_comment_matches_list(en, en_text):
            report.error(path, f"<{key}> is STALE: EN comment does not match current "
                               f"English text")
        if isinstance(text, list) and isinstance(en_text, list):
            got_ph = set().union(*(placeholders(t) for t in text)) if text else set()
            en_ph = set().union(*(placeholders(t) for t in en_text)) if en_text else set()
            extra = got_ph - en_ph
            if extra:
                report.error(path, f"<{key}> full-list translation introduces "
                                   f"placeholders {sorted(extra)} that appear "
                                   f"in no English element")

    # --- DefInjected ---
    found = {}       # def_type -> canonical keys / "<key>.<idx>" elements
    full_lists = {}  # def_type -> canonical collection keys translated as full lists
    seen = {}        # def_type -> key -> first path (dedup across every root)
    folders = []
    for lang_dir in lang_dirs:
        inj_root = lang_dir / "DefInjected"
        if inj_root.is_dir():
            folders.extend((p, lang_dir.parent.parent)
                           for p in sorted(inj_root.iterdir()) if p.is_dir())
    for folder, entry_root in folders:
        def_type = folder.name
        if def_type not in sidecar.def_types:
            report.error(folder, f"folder does not match any def type in the "
                                 f"sidecar (expected one of: "
                                 f"{', '.join(sorted(sidecar.def_types))})")
            continue
        for path in sorted(folder.glob("**/*.xml")):
            entries = load_language_xml(path, report)
            for key, elem, en in entries or []:
                by_key = seen.setdefault(def_type, {})
                if key in by_key:
                    report.error(path, f"duplicate key <{key}> (also in "
                                       f"{by_key[key]})")
                    continue
                by_key[key] = path
                resolved = sidecar.lookup(def_type, key)
                if resolved is None:
                    report.error(path, elsewhere_note(sidecar, def_type, key,
                                                      lang)
                                 or f"<{key}>: not a legal injection point "
                                    f"per the sidecar (typo, or "
                                    f"expectations stale — rerun "
                                    f"Scripts/refresh-translation-"
                                    f"expectations.py)")
                    continue
                canonical, idx = resolved
                if not sidecar.conditional(def_type, canonical):
                    check_entry_root(def_roots, def_type, canonical,
                                     entry_root, path, report)
                entry = sidecar.entries[def_type][canonical]
                text = flatten_entry(elem)
                if idx is not None:
                    found.setdefault(def_type, set()).add(f"{canonical}.{idx}")
                    en_text = entry["english"][idx]
                elif entry.get("isCollection"):
                    found.setdefault(def_type, set()).add(canonical)
                    full_lists.setdefault(def_type, set()).add(canonical)
                    en_text = None
                    if not isinstance(text, list):
                        report.error(path, f"<{key}> is a collection but the "
                                           f"translation is not a <li> list")
                    else:
                        if not entry.get("fullListAllowed") \
                                and len(text) != len(entry["english"]):
                            report.error(path, f"<{key}> full-list translation has "
                                               f"{len(text)} elements, English has "
                                               f"{len(entry['english'])}")
                        check_full_list(key, text, en, entry["english"],
                                        entry.get("fullListAllowed"), path,
                                        report)
                else:
                    found.setdefault(def_type, set()).add(canonical)
                    en_text = entry["english"]
                if isinstance(text, str) and en_text is not None:
                    if placeholders(text) != placeholders(en_text):
                        report.error(path, f"<{key}> placeholders {sorted(placeholders(text))} "
                                           f"!= English {sorted(placeholders(en_text))}")
                if en is None:
                    report.warn(path, f"<{key}> has no EN: comment")
                elif en_text is not None and norm(en) != norm(en_text):
                    report.error(path, f"<{key}> is STALE: EN comment does not match "
                                       f"current English source")

    # Completeness: every required sidecar entry must be translated. A
    # required collection is satisfied by a full-list translation or by all
    # of its elements. An entire def type nobody has started translating
    # lands here too — the old per-folder walk silently skipped those (how
    # the WeaponCategoryDef labels shipped missing in all languages).
    for def_type in sorted(sidecar.def_types):
        got = found.get(def_type, set())
        for key, entry in sorted(sidecar.required(def_type).items()):
            # Defs declared in a gated compat root take their translations
            # there too — say so, or the obvious fix for the error (add the
            # key to the main tree) ships a wrong-root bug the game catches
            # only when the gate is inactive. A key that exists in only some
            # worlds on a main-tree def (a compat-root Patch added the field)
            # takes the root active in exactly those worlds instead.
            owner = def_roots.get(def_type, {}).get(key.split(".")[0])
            where = f" — belongs under {owner / 'Languages' / lang}" \
                if owner is not None and owner.parent.name == "Mods" \
                else sidecar.where_hint(entry.get("worlds"), lang)
            if not entry.get("isCollection"):
                if key not in got:
                    report.error(f"[{lang}/DefInjected/{def_type}]",
                                 f"missing <{key}> (EN: "
                                 f"{entry['english']!r}){where}")
            elif key not in full_lists.get(def_type, set()):
                for i, en_text in enumerate(entry["english"]):
                    if f"{key}.{i}" not in got:
                        report.error(f"[{lang}/DefInjected/{def_type}]",
                                     f"missing <{key}.{i}> (EN: "
                                     f"{en_text!r}){where}")
    return found


def check_workshop(root, languages, english_keyed, report):
    # .steamworkshop/Description/<Language>.txt: line 1 is the localized
    # Workshop title, line 2 blank, then the BBCode description (see the
    # toolkit's workshop.md). Nothing in that folder ships with the mod;
    # these checks keep the publishing metadata in lockstep with the shipped
    # languages:
    #   - format: the three-part layout above (error)
    #   - coupling: title line == WORKSHOP_TITLE_KEY's value for that
    #     language (error; skipped when the key is missing in that language,
    #     since the Keyed parity check already reports that)
    #   - coverage: every shipped language has a description file (warning —
    #     Steam pastes are manual, so a missing file is backlog, not
    #     breakage, and CI's non-strict release gate must not fail on it)
    #   - size: the description body must fit Steam's save limit, which is
    #     8000 UTF-8 BYTES with CRLF newlines — not characters. The Workshop
    #     edit UI only counts characters client-side, so an oversized CJK or
    #     Cyrillic paste (2-3 bytes/char) passes the visible check and then
    #     silently fails to save (observed 2026-08: PWU ja/ko/ru, UWU/UMW ru).
    #     Error over the limit, warning within the safety margin.
    # Staleness of the translated descriptions themselves is NOT checkable
    # here (they carry no EN comments); the release skill's diff of
    # English.txt against the last release tag remains the guard for that.
    desc_dir = root / ".steamworkshop" / "Description"
    if not desc_dir.is_dir():
        return
    for path in sorted(desc_dir.glob("*.txt")):
        lang = path.stem
        try:
            lines = path.read_text(encoding="utf-8").lstrip("﻿").splitlines()
        except UnicodeDecodeError:
            report.error(path, "not valid UTF-8")
            continue
        if len(lines) < 3 or not lines[0].strip() or lines[1].strip() \
                or not any(line.strip() for line in lines[2:]):
            report.error(path, "expected line 1 title, line 2 blank, then a "
                               "non-empty description")
            continue
        # Body as pasted into the edit UI: everything after the title +
        # blank separator, with the CRLF newlines a browser textarea submits.
        body_bytes = len("\r\n".join(lines[2:]).encode("utf-8"))
        if body_bytes > WORKSHOP_DESC_BYTE_LIMIT:
            report.error(path, f"description body is {body_bytes} UTF-8 bytes "
                               f"as CRLF — over Steam's "
                               f"{WORKSHOP_DESC_BYTE_LIMIT}-byte save limit "
                               "(the edit UI counts characters, so the save "
                               "fails silently); condense the text")
        elif body_bytes > WORKSHOP_DESC_BYTE_LIMIT - WORKSHOP_DESC_BYTE_MARGIN:
            report.warn(path, f"description body is {body_bytes} UTF-8 bytes "
                              f"as CRLF — within {WORKSHOP_DESC_BYTE_MARGIN} "
                              f"bytes of Steam's {WORKSHOP_DESC_BYTE_LIMIT}-"
                              "byte save limit; any growth risks silent "
                              "save failures")
        if WORKSHOP_TITLE_KEY is None:
            continue
        if lang == "English":
            keyed = english_keyed
        elif lang in languages:
            # Re-parse this language's Keyed with a throwaway report:
            # hygiene/duplicate findings were already recorded when
            # check_language read the same files, and re-reporting them
            # here would double them up.
            keyed = collect_keyed(languages[lang], Report())
        else:
            continue  # description for an unshipped language: no Keyed value to couple to
        entry = keyed.get(WORKSHOP_TITLE_KEY)
        if entry is None:
            if lang == "English":
                report.warn(path, f"<{WORKSHOP_TITLE_KEY}> not found in "
                                  "English Keyed — title coupling cannot be "
                                  "checked (is WORKSHOP_TITLE_KEY right?)")
            continue  # missing translated key is already a Keyed parity error
        value = entry[0]
        if isinstance(value, str) and lines[0] != value:
            report.error(path, f"title line {lines[0]!r} != "
                               f"<{WORKSHOP_TITLE_KEY}> {value!r} — the "
                               "Workshop title and the settings header must "
                               "change together")
    for lang in sorted(set(languages) | ({"English"} if english_keyed else set())):
        if not (desc_dir / f"{lang}.txt").is_file():
            report.warn("[.steamworkshop/Description]",
                        f"shipped language {lang} has no {lang}.txt description")


def main():
    ap = argparse.ArgumentParser(description="Validate mod translation files.")
    # Default: the shim-provided REPO_ROOT (derived from the shim's own
    # location, so the checker works from any cwd, as it always has), falling
    # back to the current working directory when run without a shim. A path
    # derived from THIS file's location would be wrong: the engine lives in
    # the shared rimworld-l10n checkout, not the consuming repo.
    ap.add_argument("--root", type=Path, default=REPO_ROOT or Path.cwd(),
                    help="repo root (default: the shim's repo, else cwd)")
    ap.add_argument("--strict", action="store_true", help="treat warnings as errors")
    args = ap.parse_args()

    if REQUIRED_DLCS is None:
        sys.exit("check_translations engine misconfigured: REQUIRED_DLCS is "
                 "None — the consuming repo's Scripts/check-translations.py "
                 "shim must assign it after importing this engine (an empty "
                 "set() is a legitimate 'no DLC required' value; None means "
                 "the shim never set it)")

    # */Mods/*/Languages picks up gated compat load roots, which nest inside the
    # version folder as <version>/Mods/<Mod Name>/ (see LoadFolders.xml).
    lang_roots = sorted(args.root.glob("*/Languages")) + \
                 sorted(args.root.glob("*/Mods/*/Languages")) + \
                 ([args.root / "Languages"] if (args.root / "Languages").is_dir() else [])
    defs_dirs = sorted(args.root.glob("*/Defs")) + \
                sorted(args.root.glob("*/Mods/*/Defs")) + \
                ([args.root / "Defs"] if (args.root / "Defs").is_dir() else [])
    if not lang_roots:
        if ALLOW_NO_KEYED_SURFACE:
            print(f"note: no Languages/ directory under {args.root} — no "
                  "translations shipped yet; checking sidecar freshness only.")
        else:
            print(f"No Languages/ directory found under {args.root}", file=sys.stderr)
            return 2

    report = Report()
    check_engine_pin_freshness(report, args.strict)
    sidecar = load_sidecar(args.root, report)
    if sidecar is None:
        return 2

    # Which load roots each world loads. A Defs/ or Languages/ root sitting
    # in no listed load folder never loads in any configuration: report it
    # and leave it out. A listed root whose gate no world activates is
    # checked in EVERY world instead, as it was before worlds existed: it
    # loads for players who have the gate, so leaving it unchecked would
    # hide its content, and check_sidecar_freshness names the missing gate.
    folders = load_folders(args.root)
    worlds = list(sidecar.worlds)
    packages = {w: world_packages(sidecar.worlds[w]) for w in worlds}

    def gate_active(load_root, world):
        conds = folders.get(load_root.resolve(), []) if folders is not None else None
        return conds is None or any(condition_holds(c, packages[world]) for c in conds)

    load_roots = {}  # load root -> [worlds that load it], discovery order
    for content_dir in lang_roots + defs_dirs:
        load_root = content_dir.parent
        if load_root in load_roots:
            continue
        if folders is not None and load_root.resolve() not in folders:
            report.error("[LoadFolders.xml]",
                         f"{load_root} holds {content_dir.name}/ but is "
                         f"listed in no <li>, so the game never loads it — "
                         f"list it (gated if it is compat content) or "
                         f"remove it")
            load_roots[load_root] = []
            continue
        load_roots[load_root] = [w for w in worlds if gate_active(load_root, w)] \
            or list(worlds)

    # Hint table for keys that exist in only some worlds: the listed load
    # roots (the Languages/ a translator would create may not exist yet)
    # grouped by the exact set of worlds each is active in. Within a group
    # only the likeliest home is named: roots already holding a Languages/,
    # else those holding Defs/ or Patches/ (the version-specific compat
    # root, not its art-only sibling), else all of them.
    def tier(load_root):
        if (load_root / "Languages").is_dir():
            return 0
        return 1 if (load_root / "Defs").is_dir() \
            or (load_root / "Patches").is_dir() else 2
    hint_roots = {}
    for load_root, conds in sorted((folders or {}).items()):
        active = frozenset(w for w in worlds
                           if any(condition_holds(c, packages[w]) for c in conds))
        hint_roots.setdefault(active, []).append(load_root)
    for active, roots in hint_roots.items():
        best = min(tier(r) for r in roots)
        hint_roots[active] = [r for r in roots if tier(r) == best]

    ctx = {}  # world name -> what every check in that world reads
    for name in worlds:
        view = sidecar.view(name) if "worlds" in sidecar.meta else sidecar
        view.hint_roots = hint_roots
        w = ctx[name] = SimpleNamespace(
            view=view,
            loads=lambda load_root, name=name: name in load_roots[load_root],
            # Gates of the roots this world does not activate, for
            # check_sidecar_freshness's "add the gate" message.
            gates={r: describe_gate(c) for r, c in (folders or {}).items()
                   if describe_gate(c) and not any(
                       condition_holds(x, packages[name]) for x in c)})
        w.defs, w.def_roots = collect_defs(
            [d for d in defs_dirs if w.loads(d.parent)], view.active_packages)

    def phase(check):
        # Runs one check per world and merges the findings (Report.merge_worlds).
        reports = []
        for name in worlds:
            world_report = Report()
            check(ctx[name], world_report)
            reports.append((name, world_report))
        report.merge_worlds(reports)

    phase(lambda w, r: check_sidecar_freshness(w.defs, w.view, r, w.def_roots,
                                               w.gates))

    # A language is the union of its dirs across every root, not one dir per
    # root — see check_language. English already worked this way; the rest now
    # do too, so a gated compat root can hold the injections that may only live
    # there without being mistaken for a half-empty language of its own.
    english_dirs = []
    languages = {}   # language name -> [dirs], in load order
    for lang_root in lang_roots:
        if not load_roots[lang_root.parent]:
            continue
        for lang_dir in sorted(p for p in lang_root.iterdir() if p.is_dir()):
            if lang_dir.name == "English":
                english_dirs.append(lang_dir)
            else:
                languages.setdefault(lang_dir.name, []).append(lang_dir)

    def check_english(w, r):
        seen = {}
        dirs = [d for d in english_dirs if w.loads(d.parent.parent)]
        for lang_dir in dirs:
            check_english_definjected(lang_dir, w.view, w.def_roots, seen, r)
        w.english_keyed = collect_keyed(dirs, r)
    phase(check_english)
    english_keyed = {}
    for name in worlds:
        for key, value in ctx[name].english_keyed.items():
            english_keyed.setdefault(key, value)

    if not english_keyed:
        if ALLOW_NO_KEYED_SURFACE:
            print("note: no English Keyed strings — this mod has no Keyed "
                  "surface; DefInjected checks run against the sidecar alone.")
        else:
            print("No English Keyed strings found; nothing to check against.", file=sys.stderr)
            return 2

    found_by_lang = {}
    for lang, lang_dirs in sorted(languages.items()):
        found = found_by_lang[lang] = {}

        def check_one(w, r, lang=lang, lang_dirs=lang_dirs, found=found):
            got = check_language([d for d in lang_dirs if w.loads(d.parent.parent)],
                                 w.english_keyed, w.view, w.def_roots, r, lang)
            for def_type, keys in got.items():
                found.setdefault(def_type, set()).update(keys)
        phase(check_one)

    # Cross-language parity: any DefInjected key one language translates
    # beyond the required set (secondary fields, extra collection elements)
    # must exist in every language — a key added in one pass and forgotten in
    # the others is exactly the drift this catches. Keys compare in
    # canonical (sidecar) spelling, so index-form and handle-form
    # translations of the same field cannot false-positive. Runs once over
    # every world: found and demanded are unions across them.
    union = {}
    for found in found_by_lang.values():
        for def_type, keys in found.items():
            union.setdefault(def_type, set()).update(keys)
    demanded = {}  # def_type -> required keys expanded to element form
    for view in (ctx[name].view for name in worlds):
        for def_type in view.def_types:
            dem = demanded.setdefault(def_type, set())
            for key, entry in view.required(def_type).items():
                dem.add(key)
                if entry.get("isCollection"):
                    dem.update(f"{key}.{i}" for i in range(len(entry["english"])))
    for lang, found in sorted(found_by_lang.items()):
        for def_type, keys in sorted(union.items()):
            extra = keys - found.get(def_type, set()) \
                - demanded.get(def_type, set())
            extra = {k for k in extra
                     if not ({k.split(".")[-1], k.split(".")[-2] if
                              k.split(".")[-1].isdigit() else None}
                             & PARITY_EXEMPT_FIELDS)}
            for key in sorted(extra):
                report.error(f"[{lang}/DefInjected/{def_type}]",
                             f"missing <{key}> (translated in other languages)")

    check_workshop(args.root, languages, english_keyed, report)

    for line in report.errors:
        print(f"ERROR   {line}")
    for line in report.warnings:
        print(f"WARNING {line}")
    checked = ", ".join(sorted(languages)) or "none"
    print(f"\n{len(english_keyed)} English keys; languages checked: {checked}")
    print(f"{len(report.errors)} error(s), {len(report.warnings)} warning(s)")
    return 1 if report.errors or (args.strict and report.warnings) else 0


if __name__ == "__main__":
    sys.exit(main())
